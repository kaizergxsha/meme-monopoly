export interface GridPlacement {
  row: number;
  col: number;
  side: 'top' | 'right' | 'bottom' | 'left' | 'corner';
}

export function getCellGridPosition(cellId: number): GridPlacement {
  if (cellId === 0) return { row: 1, col: 1, side: 'corner' };
  if (cellId > 0 && cellId < 10) return { row: 1, col: cellId + 1, side: 'top' };
  if (cellId === 10) return { row: 1, col: 11, side: 'corner' };
  if (cellId > 10 && cellId < 20) return { row: cellId - 9, col: 11, side: 'right' };
  if (cellId === 20) return { row: 11, col: 11, side: 'corner' };
  if (cellId > 20 && cellId < 30) return { row: 11, col: 31 - cellId, side: 'bottom' };
  if (cellId === 30) return { row: 11, col: 1, side: 'corner' };
  return { row: 41 - cellId, col: 1, side: 'left' };
}

export function isBuyableCell(cell: BoardCellDef): boolean {
  return cell.type === 'PROPERTY' || cell.type === 'CAR' || cell.type === 'IT_UTILITY';
}
